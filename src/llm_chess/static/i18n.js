/* =================================== 로케일 헬퍼 =================================== */

/** @description 브라우저 태그를 비교 가능한 형태로 정규화합니다. */
function _normalizeTag(tag) {
  return String(tag || "").trim().replace(/_/g, "-").toLowerCase();
}

/** @description 지원 목록에서 대소문자와 밑줄을 무시하고 정확한 태그를 찾습니다. */
function _exactLocale(tag) {
  const normalized = _normalizeTag(tag);
  return SUPPORTED_LOCALES.find((locale) => _normalizeTag(locale) === normalized) || null;
}

/** @description 지역 태그를 제품의 지원 로케일로 변환합니다. */
function _mapLocale(tag) {
  const normalized = _normalizeTag(tag);
  const exact = _exactLocale(normalized);
  if (exact) {
    return exact;
  }
  if (/^ko-/.test(normalized)) {
    return "ko";
  }
  if (/^ja-/.test(normalized)) {
    return "ja";
  }
  if (/^es-/.test(normalized)) {
    return "es";
  }
  if (/^fr-/.test(normalized)) {
    return "fr";
  }
  if (/^de-/.test(normalized)) {
    return "de";
  }
  if (["zh-cn", "zh-sg", "zh-my"].includes(normalized)) {
    return "zh-Hans";
  }
  if (["zh-tw", "zh-hk", "zh-mo"].includes(normalized)) {
    return "zh-Hant";
  }
  if (normalized === "zh") {
    return "zh-Hans";
  }
  return null;
}

/** @description 저장된 로케일을 읽되 브라우저 저장소 오류는 현재 탭 사용을 막지 않게 합니다. */
function _readStoredLocale() {
  try {
    return window.localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

/** @description 로케일을 저장하고 저장소 오류가 있어도 메모리 상태는 유지합니다. */
function _storeLocale(locale) {
  try {
    window.localStorage.setItem(STORAGE_KEY, locale);
  } catch { /* 저장소가 막혀도 현재 탭 상태는 계속 사용합니다. */ }
}

/** @description 브라우저 언어 우선순위로 초기 로케일을 선택합니다. */
function _detectLocale() {
  const stored = _exactLocale(_readStoredLocale());
  if (stored) {
    return stored;
  }
  const candidates = Array.isArray(navigator.languages) ? [...navigator.languages] : [];
  if (navigator.language && !candidates.some((candidate) => _normalizeTag(candidate) === _normalizeTag(navigator.language))) {
    candidates.push(navigator.language);
  }
  for (const candidate of candidates) {
    const locale = _mapLocale(candidate);
    if (locale) {
      return locale;
    }
  }
  return "en";
}

/** @description 카탈로그 문자열의 자리표시자를 치환합니다. */
function _interpolate(template, values) {
  return template.replace(/\{([a-zA-Z0-9_.-]+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

/** @description 서버의 알려진 한국어 오류를 안정적인 카탈로그 키로 변환합니다. */
function _serverErrorKey(detail) {
  if (detail === "진행 중인 게임이 없습니다. 먼저 게임을 시작하세요.") {
    return { key: "error.noGame", values: {} };
  }
  if (detail === "게임이 이미 끝났습니다.") {
    return { key: "error.gameOver", values: {} };
  }
  const turnMatch = detail.match(/^현재 (사람|LLM) 차례가 아닙니다\.$/);
  if (turnMatch) {
    return {
      key: "error.wrongTurn",
      values: { actorKey: turnMatch[1] === "사람" ? "actor.human" : "actor.llm" },
    };
  }
  const illegalMoveMatch = detail.match(/^불법 수입니다:\s*(.+)$/);
  if (illegalMoveMatch) {
    return { key: "error.illegalMove", values: { move: illegalMoveMatch[1] } };
  }
  if (detail.includes("무르기") || detail.includes("되돌")) {
    return { key: "error.takeback", values: {} };
  }
  if (detail.includes("기권")) {
    return { key: "error.resign", values: {} };
  }
  return null;
}


/* =================================== 공개 인터페이스 =================================== */

/** @description 현재 카탈로그에서 문자열을 반환합니다. */
function translate(key, values = {}) {
  const template = CATALOGS[currentLocale][key];
  if (typeof template !== "string") {
    throw new Error(`Missing i18n key: ${key}`);
  }
  return _interpolate(template, values);
}

/** @description 현재 언어로 다시 그릴 수 있는 오류 정보를 Error에 담습니다. */
function localizedError(key, values = {}) {
  const error = new Error(key);
  error.i18n = { key, values };
  return error;
}

/** @description 알려진 서버 오류를 안정적인 오류 정보로 만들고 나머지는 일반 오류로 바꿉니다. */
function serverError(detail) {
  const mapped = typeof detail === "string" ? _serverErrorKey(detail) : null;
  if (!mapped) {
    return localizedError("error.generic");
  }
  return localizedError(mapped.key, mapped.values);
}

/** @description 유효한 로케일을 현재 탭과 저장소에 적용합니다. */
function setLocale(locale) {
  const canonical = _exactLocale(locale);
  if (!canonical) {
    return false;
  }
  currentLocale = canonical;
  _storeLocale(canonical);
  document.documentElement.lang = canonical;
  document.title = translate("meta.title");
  document.querySelector('meta[name="description"]').content = translate("meta.description");
  listeners.forEach((listener) => listener(canonical));
  return true;
}

/** @description 로케일 변경 리스너를 등록합니다. */
function subscribe(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

